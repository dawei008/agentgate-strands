// 同函数（cronEngine.humanize）两条缺陷，一起修一起钉：
//
// ① cron-humanize-enumerates-all-minutes（P2）：分钟为 `*` 且小时非全集时，
//    周期判定只认 raw 正则 `*/n`，裸 `*` 落到兜底分支把 60 个分钟逐项枚举
//    （`* 9-17 * * *` → 「…的第 0、1、2、…、59 分」，撑爆预览区）。
//    口径与小时侧 periodStep 同一原则：判解析后的**集合**——`*`、`0-59`、
//    `0/1`、`*/1` 是同义写法，读出来必须一致。
// ② cron-humanize-hourly-extra-space（P3）：兜底分支「每小时」与「的第」之间
//    多一个空格（`0,30 * * * *` → 「每小时 的第 0、30 分」），与同函数单分钟
//    分支「每小时的第 0 分」排版不一致。小时枚举列表与「的第」之间的空格保留。
//
// 人话描述是保存前唯一的频率-成本护栏（每次触发都是付费评估），可读性即安全性。
import { describe, expect, it } from "vitest";
import { humanize, parseCron } from "../src/pages/plan/cronEngine";

const h = (expr: string) => humanize(parseCron(expr));

describe("缺陷①：分钟铺满 0–59 全域 → 「每分钟」，不枚举 60 个分钟", () => {
  it("* 9-17 * * * → 小时范围 + 每分钟（本缺陷专属锚点）", () => {
    expect(h("* 9-17 * * *")).toBe("每天 09:00–17:59 之间每分钟 UTC 运行");
  });

  it("EB 六段式同语义同人话", () => {
    expect(h("cron(* 9-17 * * ? *)")).toBe("每天 09:00–17:59 之间每分钟 UTC 运行");
  });

  it("枚举撑爆的直接证据：描述里不出现分钟逐项列表", () => {
    const txt = h("* 9-17 * * *") ?? "";
    expect(txt).not.toContain("59 分");
    expect(txt.length).toBeLessThan(30);
  });

  it("同义写法（*/1、0-59、0/1）与 * 读出来一致", () => {
    const want = h("* 9-17 * * *");
    expect(h("*/1 9-17 * * *")).toBe(want);
    expect(h("0-59 9-17 * * *")).toBe(want);
    expect(h("0/1 9-17 * * *")).toBe(want);
  });

  it("小时全集时同口径（* * * * * 及其同义写法 → 每分钟）", () => {
    expect(h("* * * * *")).toBe("每分钟 UTC 运行");
    expect(h("0-59 * * * *")).toBe("每分钟 UTC 运行");
    expect(h("*/1 * * * *")).toBe("每分钟 UTC 运行");
  });

  it("小时是枚举集合（非连续范围）→ 「N 时 内每分钟」", () => {
    expect(h("* 9,12 * * *")).toBe("每天 9、12 时 内每分钟 UTC 运行");
  });

  it("回归钉：*/15 各形态文案不变（原本就对）", () => {
    expect(h("*/15 9-17 * * *")).toBe("每天 09:00–17:59 之间每 15 分钟 UTC 运行");
    expect(h("*/15 * * * *")).toBe("每 15 分钟 UTC 运行");
  });

  it("回归钉：稀疏分钟集合仍逐项列", () => {
    expect(h("0,30 9-17 * * *"))
      .toBe("每天 09 点、10 点、11 点、12 点、13 点、14 点、15 点、16 点、17 点 的第 0、30 分 UTC 运行");
    expect(h("5,10,15 9 * * *")).toBe("每天 09 点 的第 5、10、15 分 UTC 运行");
  });
});

describe("缺陷②：「每小时」直接接「的第」，无多余空格", () => {
  it("0,30 * * * * → 每小时的第 0、30 分（本缺陷专属锚点）", () => {
    expect(h("0,30 * * * *")).toBe("每小时的第 0、30 分 UTC 运行");
  });

  it("EB 六段式同刑", () => {
    expect(h("cron(0,30 * ? * * *)")).toBe("每小时的第 0、30 分 UTC 运行");
  });

  it("回归钉：单分钟整点分支文案不变（cron-fix 已定型）", () => {
    expect(h("0 * * * *")).toBe("每小时的第 0 分 UTC 运行");
  });

  it("回归钉：小时枚举列表与「的第」之间的空格保留", () => {
    expect(h("5,10,15 9 * * *")).toBe("每天 09 点 的第 5、10、15 分 UTC 运行");
  });
});
