// 缺陷 2 回归：小时字段是全集时，人话描述曾把 24 个小时全枚举
// （`0 * * * *` → 「每天 00、01、…、23 点的第 0 分」），把预览区撑爆。
//
// 口径：小时集合若是「从下界 0 起、等步长、到上界 23 为止且 24 能被步长整除」
// 的全覆盖序列，就用周期说法（step=1 → 「每小时」；step>1 → 「每 n 小时」）；
// 否则才逐个列出小时。判据取自解析后的**集合**而非 raw 写法，所以语义等价的
// `*/6` 与 `0/6`（缺陷 1 修完后同集合）读出来必须一模一样。
// 24 不能被步长整除时（如 0,5,10,15,20 点）「每 5 小时」是假的——跨日那一段
// 只隔 4 小时——这种情况仍逐个列出（≤12 项，不会撑爆）。
import { describe, expect, it } from "vitest";
import { humanize, parseCron } from "../src/pages/plan/cronEngine";

const h = (expr: string) => humanize(parseCron(expr));

describe("humanize：整点小时不再枚举 24 个小时（缺陷 2）", () => {
  it("0 * * * * → 每小时的第 0 分（不枚举）", () => {
    expect(h("0 * * * *")).toBe("每小时的第 0 分 UTC 运行");
  });

  it("枚举撑爆的直接证据：描述里不出现 23 点，也不出现列表分隔号", () => {
    const txt = h("0 * * * *") ?? "";
    expect(txt).not.toContain("23");
    expect(txt).not.toContain("、");
    expect(txt.length).toBeLessThan(20);
  });

  it("非 0 分钟 / 叠加周几前缀时仍成立", () => {
    expect(h("30 * * * *")).toBe("每小时的第 30 分 UTC 运行");
    expect(h("0 * * * 1")).toBe("每周一 每小时的第 0 分 UTC 运行");
    expect(h("0 * 15 * *")).toBe("每月 15 日 每小时的第 0 分 UTC 运行");
  });

  it("小时全集的等价写法（0-23 / 0/1 / *）读出来一致", () => {
    expect(h("0 0-23 * * *")).toBe("每小时的第 0 分 UTC 运行");
    expect(h("0 0/1 * * *")).toBe("每小时的第 0 分 UTC 运行");
    expect(h("cron(0 * ? * * *)")).toBe("每小时的第 0 分 UTC 运行");
  });
});

describe("humanize：等步长小时子集说「每 n 小时」（不枚举）", () => {
  it("回归：*/n 形式原本就对，不得变形", () => {
    expect(h("0 */2 * * *")).toBe("每 2 小时（整点） UTC 运行");
    expect(h("0 */6 * * *")).toBe("每 6 小时（整点） UTC 运行");
    expect(h("15 */6 * * *")).toBe("每 6 小时的第 15 分 UTC 运行");
  });

  it("a/b 形式（缺陷 1 修完后同集合）与 */b 读出来一致", () => {
    expect(h("0 0/6 * * *")).toBe("每 6 小时（整点） UTC 运行");
    expect(h("15 0/6 * * *")).toBe("每 6 小时的第 15 分 UTC 运行");
    expect(h("cron(0 0/6 ? * * *)")).toBe("每 6 小时（整点） UTC 运行");
    expect(h("0 0/12 * * *")).toBe("每 12 小时（整点） UTC 运行");
    expect(h("0 0,12 * * *")).toBe("每 12 小时（整点） UTC 运行");
  });

  // 以下每条都是「不能说每 n 小时」的一个独立理由，各自单独一个 it：
  // 挤在一个 it 里时第一条失败就停，后面几条的保护会被掩盖成假绿。
  it("起点不是 0 点 → 列小时（「每 6 小时」会丢掉「从 02 点起」）", () => {
    expect(h("0 2/6 * * *")).toBe("每天 02、08、14、20 点的第 0 分 UTC 运行");
  });

  it("只覆盖上半天 → 列小时（0-12/6 得 0、6、12，18 点不跑）", () => {
    expect(h("0 0-12/6 * * *")).toBe("每天 00、06、12 点的第 0 分 UTC 运行");
  });

  it("上界差一格没铺满 → 列小时（0-22 的 23 点不跑）", () => {
    expect(h("0 0-22 * * *")).toBe("每天 00–22 点的第 0 分 UTC 运行");
  });

  it("24 不能被步长整除 → 列小时（20 点到次日 0 点只隔 4 小时）", () => {
    expect(h("0 0/5 * * *")).toBe("每天 00、05、10、15、20 点的第 0 分 UTC 运行");
    expect(h("0 */5 * * *")).toBe("每天 00、05、10、15、20 点的第 0 分 UTC 运行");
  });

  it("步长不处处相等 → 列小时（0→6 隔 6 小时，6→18 隔 12 小时）", () => {
    expect(h("0 0,6,18 * * *")).toBe("每天 00、06、18 点的第 0 分 UTC 运行");
  });

  it("回归：单一时刻 / 小时区间 / 小时列表 / 分钟步长的说法不受影响", () => {
    expect(h("30 23 * * *")).toBe("每天 23:30 UTC 运行");
    expect(h("0 3 * * 1")).toBe("每周一 03:00 UTC 运行");
    expect(h("0 9-18 * * *")).toBe("每天 09–18 点的第 0 分 UTC 运行");
    expect(h("0 9,18 * * *")).toBe("每天 09、18 点的第 0 分 UTC 运行");
    expect(h("* * * * *")).toBe("每分钟 UTC 运行");
    expect(h("*/15 * * * *")).toBe("每 15 分钟 UTC 运行");
    expect(h("*/30 9-18 * * 1-5")).toBe("每周一至周五 09:00–18:59 之间每 30 分钟 UTC 运行");
  });
});
